def render_pick_detail(slot: str, player: str, event: str, model_win: str, books_win: str, odds: str,
                       skills: dict, note: str, out_path: str) -> str:
    """Carousel slide for one pick. slot: win/value/fade/sleeper (picks the Sharpie mark).
    skills: {"OTT"|"APP"|"ARG"|"PUTT": ("+0.45", "#12")}; missing keys render as em dashes."""
    tokens = {"player": player, "event": event, "model_win": model_win, "books_win": books_win,
              "odds": odds, "note": note}
    for key in ("OTT", "APP", "ARG", "PUTT"):
        value, rank = skills.get(key, ("—", "—"))
        tokens[f"sg_{key}"] = value
        tokens[f"rank_{key}"] = rank
    return _fill_and_render(f"pick_{slot}.svg", tokens, out_path)


def render_stat_list(title: str, subtitle: str, header: str, rows: list, note: str, out_path: str) -> str:
    """Carousel top-5 list. rows: up to 5 (name, value) pairs; the top value gets the Sharpie circle."""
    rows = (list(rows)[:5] + [("", "")] * 5)[:5]
    tokens = {"title": title, "subtitle": subtitle, "header": header, "note": note}
    for i, (name, value) in enumerate(rows, start=1):
        tokens[f"name_{i}"] = name
        tokens[f"value_{i}"] = value
    return _fill_and_render("stat_list.svg", tokens, out_path)


def render_closer(event: str, out_path: str) -> str:
    """Carousel closing slide ("RECEIPTS SUNDAY.")."""
    return _fill_and_render("closer.svg", {"event": event}, out_path)


SLOT_TEMPLATES = {"win": "card_win", "value": "card_value", "fade": "card_fade", "sleeper": "card_sleeper"}
CARD_BOX = (100, 59, 980, 1291)   # the 5:7 card's bounds on the 1080x1350 slide (see tools/build_markup.py)


def _photo_data_uri(photo_path: str, style: str) -> str:
    """Library photo (already cropped to the card window) as a JPEG data: URI; style "brand" = duotone
    in the card inks so photos from different sources read as one deck."""
    import base64
    import io
    from PIL import Image, ImageEnhance, ImageOps
    im = Image.open(photo_path).convert("RGB")
    if style == "brand":
        g = ImageOps.autocontrast(ImageOps.grayscale(im), cutoff=1)
        im = ImageEnhance.Contrast(ImageOps.colorize(g, black="#1E2A22", white="#F2ECDC", mid="#7E8A70")).enhance(1.08)
    buf = io.BytesIO()
    im.save(buf, "JPEG", quality=86)
    return "data:image/jpeg;base64," + base64.b64encode(buf.getvalue()).decode()


def render_playing_card(slot: str, player: str, event: str, model_win: str, books_win: str, odds: str,
                        skills: dict, note: str, out_path: str, photo_path: str = None, credit: str = "",
                        style: str = "color") -> str:
    """Carousel playing card for one pick. With photo_path (from tools/player_photos.lookup) the photo fills
    the window with its credit; without one, the player's initials do. style: "color" or "brand"."""
    tokens = {"player": player, "event": event, "model_win": model_win, "books_win": books_win,
              "odds": odds, "note": note}
    for key in ("OTT", "APP", "ARG", "PUTT"):
        value, rank = skills.get(key, ("—", "—"))
        tokens[f"sg_{key}"] = value
        tokens[f"rank_{key}"] = rank
    if photo_path:
        tokens["photo"] = _photo_data_uri(photo_path, style)
        tokens["credit"] = credit
        template = f"{SLOT_TEMPLATES[slot]}.svg"
    else:
        tokens["initials"] = "".join(part[0] for part in player.replace(".", " ").split() if part[:1].isalpha())[:3].upper()
        template = f"{SLOT_TEMPLATES[slot]}_nophoto.svg"
    return _fill_and_render(template, tokens, out_path)


def render_hand(card_paths: list, event: str, out_path: str) -> str:
    """'This Week's Hand' cover: the rendered playing cards cut out and fanned like a poker hand."""
    import io
    from PIL import Image, ImageDraw
    bg_path = out_path + ".bg.png"
    _fill_and_render("hand_cover.svg", {"event": event}, bg_path)
    bg = Image.open(bg_path).convert("RGBA")
    os.remove(bg_path)
    scale = bg.width / 1080
    box = tuple(int(v * scale) for v in CARD_BOX)
    n = len(card_paths)
    angles = [-15, -5, 5, 15][:n] if n == 4 else [(-15 + 30 * i / max(n - 1, 1)) for i in range(n)]
    xs = [330, 470, 610, 750][:n] if n == 4 else [int(330 + 420 * i / max(n - 1, 1)) for i in range(n)]
    for path, angle, x in zip(card_paths, angles, xs):
        card = Image.open(path).convert("RGBA").crop(box)
        mask = Image.new("L", card.size, 0)
        ImageDraw.Draw(mask).rounded_rectangle((0, 0, card.width - 1, card.height - 1), radius=int(40 * scale), fill=255)
        card.putalpha(mask)
        card = card.resize((int(400 * scale), int(560 * scale)), Image.LANCZOS)
        rotated = card.rotate(-angle, expand=True, resample=Image.BICUBIC)
        bg.alpha_composite(rotated, (int(x * scale) - rotated.width // 2, int((340 + abs(angle) * 3) * scale)))
    bg.convert("RGB").save(out_path)
    return out_path


def render_reel(slides: list, out_path: str, fps: int = 30) -> str:
    """Vertical 1080x1920 Reel (H.264, silent; music is added in the Instagram app).
    slides: [{"path": 4:5 png, "seconds": float, "top": heading, "sub": one-line meaning, "bottom": why line}]
    (text keys optional). Each card is "dealt" in: a quick snap with a small settling rotation, then a slow
    push-in; text sits above/below the card, inside Instagram's safe area. Hard cuts, no cross-fade. Needs ffmpeg."""
    import shutil
    import subprocess
    from PIL import Image, ImageDraw, ImageFont
    if not shutil.which("ffmpeg"):
        raise RuntimeError("ffmpeg not installed; can't build the Reel")
    W, H = 1080, 1920
    PAPER, INK, RED, PENCIL = (0xF2, 0xEC, 0xDC), (0x1E, 0x2A, 0x22), (0xD3, 0x26, 0x1F), (0x6E, 0x68, 0x57)
    CARD_W, CARD_TOP = 900, 400                      # card 900x1125, y 400-1525; text 250-385 and 1550-1640
    font = lambda fam, size: ImageFont.truetype(os.path.join(FONT_DIR, FONT_FILES[fam]), size)

    def fit(draw, text, fam, size, max_w):
        while size > 18 and draw.textlength(text, font=font(fam, size)) > max_w:
            size -= 2
        return font(fam, size)

    def background(sl):
        bg = Image.new("RGB", (W, H), PAPER)
        d = ImageDraw.Draw(bg)
        if sl.get("top"):
            f = fit(d, sl["top"], "Anton", 76, 960)
            d.text((W // 2, 285), sl["top"], font=f, fill=INK, anchor="mm")
        if sl.get("sub"):
            f = fit(d, sl["sub"], "Barlow SemiBold", 36, 960)
            d.text((W // 2, 352), sl["sub"], font=f, fill=PENCIL, anchor="mm")
        if sl.get("bottom"):
            f = fit(d, sl["bottom"], "Permanent Marker", 44, 960)
            d.text((W // 2, 1600), sl["bottom"], font=f, fill=RED, anchor="mm")
        return bg

    def card_img(path):
        img = Image.open(path).convert("RGBA")
        return img.resize((CARD_W, int(img.height * CARD_W / img.width)), Image.LANCZOS)

    deal = 7                                         # frames for the snap-in
    proc = subprocess.Popen(
        ["ffmpeg", "-y", "-loglevel", "error", "-f", "rawvideo", "-pix_fmt", "rgb24", "-s", f"{W}x{H}",
         "-r", str(fps), "-i", "-", "-c:v", "libx264", "-preset", "medium", "-crf", "20",
         "-pix_fmt", "yuv420p", "-movflags", "+faststart", out_path],
        stdin=subprocess.PIPE)
    try:
        for sl in slides:
            bg, card = background(sl), card_img(sl["path"])
            n = max(int(sl.get("seconds", 1.6) * fps), deal + 1)
            for f in range(n):
                if f < deal:                         # dealt in from the right with a small settling turn
                    e = 1 - (1 - (f + 1) / deal) ** 3
                    angle, scale, dx = 3 * (1 - e), 1.0, int(420 * (1 - e))
                else:                                # slow push-in
                    angle, dx = 0.0, 0
                    scale = 1.0 + 0.02 * (f - deal) / max(n - deal, 1)
                c = card.resize((int(card.width * scale), int(card.height * scale)), Image.BICUBIC)
                if angle:
                    c = c.rotate(angle, expand=True, resample=Image.BICUBIC)
                frame = bg.copy()
                cx, cy = W // 2 + dx, CARD_TOP + card.height // 2
                frame.paste(c, (cx - c.width // 2, cy - c.height // 2), c)
                proc.stdin.write(frame.tobytes())
    finally:
        proc.stdin.close()
        rc = proc.wait()
    if rc != 0:
        raise RuntimeError(f"ffmpeg failed (exit {rc})")
    return out_path

